def format_tiebreaker_prompt(
    original_user_prompt: str,
    results: dict,
) -> str:
    """构建仲裁 user prompt

    Args:
        original_user_prompt: 原始评判的 user prompt（包含任务目标、步骤等）
        results: Dict[model_name, TrajectoryJudgeResult]

    Returns:
        仲裁 prompt
    """
    model_sections = []
    for model_name, result in results.items():
        if result.result.value == "llm_error":
            continue
        section = f"### 模型: {model_name}\n"
        section += f"- 评判结果: {result.result.value}\n"
        section += f"- 置信度: {result.confidence:.2f}\n"
        if result.error_cause:
            cause_labels = ", ".join(result.error_cause)
            section += f"- 错误原因: {cause_labels}\n"
        if result.error_analysis:
            section += f"- 错误分析: {result.error_analysis}\n"
        if result.analysis:
            section += f"- 分析过程:\n{result.analysis}\n"
        model_sections.append(section)

    model_results_text = "\n".join(model_sections)

    return f"""{original_user_prompt}

---

## 各模型评判结果（出现平票，需要你仲裁）

{model_results_text}

请综合以上所有模型的分析和截图内容，做出最终裁决。"""


# ============================================================
# User Prompt 模板
# ============================================================

def format_user_prompt(
    instruction: str,
    steps: list,
    agent_status: str = "unknown",
    num_images: int = 0,
    task_kind: Optional[str] = None,
    task_hint: Optional[str] = None,
) -> str:
    """
    格式化用户 Prompt

    Args:
        instruction: 任务目标
        steps: 步骤列表，每个元素包含 step_index, thought, action
        agent_status: Agent 自己报告的最终状态
        num_images: 图片数量
        task_kind: 来自 tasks.jsonl 的 \"正例\" / \"负例\"；为 None 时不附加评测集标注块

    Returns:
        格式化后的 prompt
    """
    # 构建步骤描述
    steps_lines = []
    for step in steps:
        step_idx = step.get("step_index", 0)
        thought = step.get("thought", "").strip()
        action = step.get("action", {})
        action_type = action.get("action_type", "unknown")
        takeover_input = step.get("takeover_input", "")

        # 构建动作描述 (尽量详细)
        action_desc = f"动作类型: {action_type}"
        if action_type in ("click", "long_press", "double_tap"):
            x, y = action.get("x"), action.get("y")
            if x is not None and y is not None:
                action_desc += f", 坐标: ({x}, {y})"
        elif action_type in ("swipe", "drag"):
            sx, sy = action.get("start_x"), action.get("start_y")
            ex, ey = action.get("end_x"), action.get("end_y")
            if sx is not None:
                action_desc += f", 起点: ({sx}, {sy}), 终点: ({ex}, {ey})"
        elif action_type == "type":
            text = action.get("text", "")
            action_desc += f", 输入文本: \"{text[:80]}\""
        elif action_type == "open_app":
            app_name = action.get("app_name", "")
            action_desc += f", 应用: {app_name}"
        elif action_type == "takeover" or action_type == "take_over":
            tag = action.get("tag", "")
            ask_text = action.get("text", "") or action.get("summarize", "")
            if tag:
                action_desc += f", 接管标签: {tag}"
            action_desc += f", Agent 提问: \"{ask_text[:100]}\""
            if takeover_input:
                action_desc += f", 用户输入: \"{takeover_input[:100]}\""
        elif action_type in ("finished", "terminate"):
            status = action.get("status", "unknown")
            text = action.get("text", "") or action.get("summary", "") or action.get("summarize", "")
            action_desc += f", 状态: {status}"
            if text:
                action_desc += f", 说明: \"{text[:120]}\""
        elif action_type == "wait":
            dur = action.get("duration", "")
            if dur:
                action_desc += f", 等待: {dur}ms"
        elif action_type in ("navigate_home", "navigate_back"):
            pass  # 无额外信息

        step_line = f"**步骤 {step_idx + 1}:**\n"
        if thought:
            step_line += f"  - 思考: {thought[:200]}{'...' if len(thought) > 200 else ''}\n"
        step_line += f"  - {action_desc}"
        if takeover_input and action_type != "takeover" and action_type != "take_over":
            step_line += f"\n  - 用户接管输入: \"{takeover_input[:100]}\""

        steps_lines.append(step_line)

    steps_description = "\n\n".join(steps_lines)

    if task_kind == "负例":
        rules_body = USER_BLOCK_TASK_KIND_NEGATIVE
    elif task_kind == "正例":
        rules_body = USER_BLOCK_TASK_KIND_POSITIVE
    else:
        rules_body = ""

    if task_kind in ("正例", "负例"):
        task_annotation_block = (
            "## 评测集标注\n"
            f"本题在测试集中标注为：**{task_kind}**。\n\n"
            f"{rules_body}\n\n"
        )
    else:
        task_annotation_block = ""

    # 任务评判提示（来自 task_hints.jsonl，匹配成功时注入到任务目标下方）
    if task_hint:
        task_hint_block = f"\n> **评判提示：** {task_hint}\n"
    else:
        task_hint_block = ""

    return USER_PROMPT_TEMPLATE.format(
        task_annotation_block=task_annotation_block,
        instruction=instruction,
        task_hint_block=task_hint_block,
        total_steps=len(steps),
        steps_description=steps_description,
        agent_status=agent_status,
        num_images=num_images,
    )
