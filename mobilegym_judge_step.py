def original_step_response_from_item(item: Dict[str, Any]) -> Tuple[str, str, Optional[Dict[str, Any]], str]:
    response = compact(item.get("original_response"))
    think = compact(item.get("original_think"))
    answer = compact(item.get("original_answer"))
    raw_action = item.get("original_action")
    action = raw_action if isinstance(raw_action, dict) else None
    if action is None and response:
        parsed_think, parsed_answer, parsed_action = parse_model_response(response)
        think = think or parsed_think
        answer = answer or parsed_answer
        action = parsed_action
    return think, answer, action, compact(item.get("original_response_path"))


def normalize_action_type(action: Optional[Dict[str, Any]]) -> str:
    if not isinstance(action, dict):
        return ""
    for key in ("action_type", "type", "action"):
        value = action.get(key)
        if isinstance(value, str) and value.strip():
            raw = value.strip().lower()
            break
    else:
        raw = ""
    if raw in {"click", "tap"}:
        return "click"
    if raw in {"double_tap", "doubletap", "double tap"}:
        return "double_tap"
    if raw in {"longpress", "long_press", "long press"}:
        return "longpress"
    if raw in {"swipe", "scroll"}:
        return "swipe"
    if raw in {"drag"}:
        return "drag"
    if raw in {"type", "input", "text"}:
        return "type"
    if raw in {"awake", "launch", "open_app"}:
        return "awake"
    if raw in {"complete", "finish", "finished", "done"}:
        return "complete"
    if raw in {"wait", "back", "home", "recent", "enter", "answer", "abort"}:
        return raw
    return raw


def numeric_value(value: Any) -> Optional[float]:
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        try:
            return float(value.strip())
        except ValueError:
            return None
    return None


def point_from_value(value: Any) -> Optional[Tuple[float, float]]:
    if isinstance(value, dict):
        x = numeric_value(value.get("x"))
        y = numeric_value(value.get("y"))
        if x is not None and y is not None:
            return x, y
    if isinstance(value, (list, tuple)) and len(value) >= 2:
        x = numeric_value(value[0])
        y = numeric_value(value[1])
        if x is not None and y is not None:
            return x, y
    return None


def action_point(action: Optional[Dict[str, Any]]) -> Optional[Tuple[float, float]]:
    if not isinstance(action, dict):
        return None
    for key in ("coordinate", "coordinates", "point", "position", "target", "tap_point", "click_point"):
        point = point_from_value(action.get(key))
        if point is not None:
            return point
    x = numeric_value(action.get("x"))
    y = numeric_value(action.get("y"))
    if x is not None and y is not None:
        return x, y
    return None


def action_text(action: Optional[Dict[str, Any]]) -> str:
    if not isinstance(action, dict):
        return ""
    for key in ("text", "content", "input_text", "value"):
        value = action.get(key)
        if isinstance(value, str):
            return value.strip()
    return ""


def swipe_points(action: Optional[Dict[str, Any]]) -> Optional[Tuple[Tuple[float, float], Tuple[float, float]]]:
    if not isinstance(action, dict):
        return None
    start = None
    end = None
    for key in ("start", "from", "start_point", "start_coordinate"):
        start = point_from_value(action.get(key))
        if start is not None:
            break
    for key in ("end", "to", "end_point", "end_coordinate"):
        end = point_from_value(action.get(key))
        if end is not None:
            break
    if start is not None and end is not None:
        return start, end

    points = action.get("points") or action.get("path")
    if isinstance(points, list) and len(points) >= 2:
        start = point_from_value(points[0])
        end = point_from_value(points[-1])
        if start is not None and end is not None:
            return start, end

    x1 = numeric_value(action.get("x1"))
    y1 = numeric_value(action.get("y1"))
    x2 = numeric_value(action.get("x2"))
    y2 = numeric_value(action.get("y2"))
    if x1 is not None and y1 is not None and x2 is not None and y2 is not None:
        return (x1, y1), (x2, y2)
    return None


def point_distance(first: Tuple[float, float], second: Tuple[float, float]) -> float:
    return math.hypot(first[0] - second[0], first[1] - second[1])


def swipe_direction(points: Tuple[Tuple[float, float], Tuple[float, float]]) -> str:
    (x1, y1), (x2, y2) = points
    dx = x2 - x1
    dy = y2 - y1
    if abs(dx) >= abs(dy):
        return "right" if dx > 0 else "left"
    return "down" if dy > 0 else "up"


def swipe_length(points: Tuple[Tuple[float, float], Tuple[float, float]]) -> float:
    return point_distance(points[0], points[1])


def action_similarity_summary(
    original_action: Optional[Dict[str, Any]],
    repredicted_action: Optional[Dict[str, Any]],
) -> Dict[str, Any]:
    original_type = normalize_action_type(original_action)
    repredicted_type = normalize_action_type(repredicted_action)
    summary: Dict[str, Any] = {
        "original_type": original_type,
        "repredicted_type": repredicted_type,
        "too_similar": False,
        "reason": "",
    }
    if not original_type or not repredicted_type:
        summary["reason"] = "missing_action_type"
        return summary
    if original_type != repredicted_type:
        summary["reason"] = "different_action_type"
        return summary

    if original_type == "click":
        original_point = action_point(original_action)
        repredicted_point = action_point(repredicted_action)
        summary["original_point"] = original_point
        summary["repredicted_point"] = repredicted_point
        if original_point is None or repredicted_point is None:
            summary["reason"] = "missing_click_point"
            return summary
        distance = point_distance(original_point, repredicted_point)
        summary["point_distance"] = round(distance, 3)
        if distance <= 80.0:
            summary["too_similar"] = True
            summary["reason"] = "same_click_region"
        else:
            summary["reason"] = "different_click_region"
        return summary

    if original_type == "swipe":
        original_points = swipe_points(original_action)
        repredicted_points = swipe_points(repredicted_action)
        summary["original_swipe"] = original_points
        summary["repredicted_swipe"] = repredicted_points
        if original_points is None or repredicted_points is None:
            summary["reason"] = "missing_swipe_points"
            return summary
        original_direction = swipe_direction(original_points)
        repredicted_direction = swipe_direction(repredicted_points)
        start_distance = point_distance(original_points[0], repredicted_points[0])
        original_length = swipe_length(original_points)
        repredicted_length = swipe_length(repredicted_points)
        length_delta = abs(original_length - repredicted_length)
        length_base = max(original_length, repredicted_length, 1.0)
        summary.update(
            {
                "original_direction": original_direction,
                "repredicted_direction": repredicted_direction,
                "start_distance": round(start_distance, 3),
                "length_delta_ratio": round(length_delta / length_base, 3),
            }
        )
        if original_direction == repredicted_direction and start_distance <= 50.0 and length_delta / length_base <= 0.10:
            summary["too_similar"] = True
            summary["reason"] = "same_swipe_behavior"
        else:
            summary["reason"] = "different_swipe_behavior"
        return summary

    if original_type == "type":
        original_text = action_text(original_action)
        repredicted_text = action_text(repredicted_action)
        summary["original_text"] = original_text
        summary["repredicted_text"] = repredicted_text
        if original_text and original_text == repredicted_text:
            summary["too_similar"] = True
            summary["reason"] = "same_type_text"
        elif not repredicted_text:
            summary["reason"] = "missing_repredicted_text"
        else:
            summary["reason"] = "different_type_text"
        return summary

    if original_type in {"wait", "back", "home", "enter", "done"}:
        summary["too_similar"] = True
        summary["reason"] = "same_non_target_action"
        return summary

    summary["reason"] = "same_unhandled_action_type"
    return summary


