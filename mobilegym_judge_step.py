def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8-sig") as f:
        return json.load(f)


def write_json(path: Path, payload: Any, indent: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=None if indent == 0 else indent)
        f.write("\n")


def compact(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    try:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    except TypeError:
        return str(value)


def judge_context_fields(item: Dict[str, Any]) -> Dict[str, Any]:
    context: Dict[str, Any] = {}
    for key in JUDGE_CONTEXT_KEYS:
        value = item.get(key)
        if value is None or value == "":
            continue
        context[key] = value if isinstance(value, bool) else compact(value)
    return context


def extract_tag(regex: re.Pattern[str], text: str) -> str:
    match = regex.search(text or "")
    return (match.group(1) or "").strip() if match else ""


def extract_first_json(text: str) -> Optional[str]:
    start = text.find("{")
    if start < 0:
        return None
    in_str = False
    esc = False
    depth = 0
    for index in range(start, len(text)):
        ch = text[index]
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
            continue
        if ch == '"':
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]
    return None


def parse_json_object(text: str) -> Optional[Dict[str, Any]]:
    raw = str(text or "").strip()
    if not raw:
        return None
    candidates = [raw]
    first_json = extract_first_json(raw)
    if first_json and first_json != raw:
        candidates.append(first_json)
    for candidate in candidates:
        try:
            parsed = json.loads(candidate)
        except Exception:
            continue
        if isinstance(parsed, dict):
            return parsed
    return None


def parse_model_response(response: str) -> Tuple[str, str, Optional[Dict[str, Any]]]:
    think = extract_tag(THINK_RE, response)
    answer = extract_tag(ANSWER_RE, response)
    action = parse_json_object(answer) if answer else parse_json_object(response)
    return think, answer, action


def normalize_items(payload: Any) -> List[Dict[str, Any]]:
    if isinstance(payload, dict) and isinstance(payload.get("results"), list):
        items = payload["results"]
    elif isinstance(payload, list):
        items = payload
    elif isinstance(payload, dict):
        items = [payload]
    else:
        raise ValueError("input JSON must be an object, list, or object with results")
    return [item for item in items if isinstance(item, dict)]


