def truncate_text(text: str, limit: int = 1200) -> str:
    text = compact(text)
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "...(已截断)"


def nested_get(data: Dict[str, Any], path: Tuple[str, ...]) -> Any:
    current: Any = data
    for key in path:
        if not isinstance(current, dict):
            return None
        current = current.get(key)
    return current


def failure_context_from_item(item: Dict[str, Any]) -> str:
    fields: List[Tuple[str, Tuple[str, ...]]] = [
        ("wrong_action_step", ("wrong_action_step",)),
        ("first_bad_state_step", ("first_bad_state_step",)),
        ("judge_reason", ("judge_reason",)),
        ("wrong_action_reason", ("wrong_action_reason",)),
        ("step_alignment_reason", ("step_alignment_reason",)),
        ("failure_mode_for_skill", ("failure_mode_for_skill",)),
        ("first_deviation_reason", ("first_deviation_reason",)),
        ("failure_summary", ("failure_summary",)),
        ("failure_reason", ("failure_reason",)),
        ("failed_step_reason", ("failed_step_reason",)),
        ("error_type", ("error_type",)),
        ("classification", ("classification",)),
        ("original_judgment", ("original_judgment",)),
        ("run_judgment", ("run_judgment",)),
        ("judgment.reason", ("judgment", "reason")),
        ("judgment.first_deviation_reason", ("judgment", "first_deviation_reason")),
    ]
    lines: List[str] = []
    seen: set[str] = set()
    for label, path in fields:
        value = nested_get(item, path)
        text = truncate_text(compact(value), 1000)
        if not text or text in seen:
            continue
        seen.add(text)
        lines.append(f"- {label}: {text}")
    if not lines:
        return "（无）"
    context = "\n".join(lines)
    return truncate_text(context, 5000)


